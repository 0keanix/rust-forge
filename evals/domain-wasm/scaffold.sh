//! notes-filter: note types shared by the app and its host tests.

/// A note shown in the app.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Note {
    pub id: u64,
    pub title: String,
    pub body: String,
}

/// The sample notes the app starts with.
pub fn sample_notes() -> Vec<Note> {
    [
        ("Groceries", "milk, eggs, bread"),
        ("Call Bob", "about the trip in May"),
        ("Rust", "read the Leptos book"),
    ]
    .into_iter()
    .zip(1..)
    .map(|((title, body), id)| Note {
        id,
        title: title.to_owned(),
        body: body.to_owned(),
    })
    .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sample_notes_have_increasing_ids() {
        let notes = sample_notes();
        assert_eq!(notes.len(), 3);
        assert!(notes.windows(2).all(|w| w[0].id < w[1].id));
    }
}
EOF
