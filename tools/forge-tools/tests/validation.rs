//! Behaviour from PRD 00a sections not covered by the AC tests (added by v-tools).
#![expect(clippy::unwrap_used, reason = "tests")]

mod common;

use std::path::Path;
use std::process::Command;

use common::{BADLY_FORMATTED_LIB, TempDir, run, stdout, write, write_crate};
use serde_json::{Value, json};

const FAILING_TEST_LIB: &str = "/// Adds one.\npub fn add_one(x: u32) -> u32 {\n    x + 1\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn adds() {\n        assert_eq!(super::add_one(1), 3);\n    }\n}\n";

/// The lock file cargo writes for the dependency-free fixture crate.
const LOCK: &str = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n";

fn git(dir: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .args(["-c", "user.name=t", "-c", "user.email=t@example.invalid"])
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(out.status.success(), "git {args:?}");
    String::from_utf8_lossy(&out.stdout).trim().to_owned()
}

/// A committed crate whose fmt/check/clippy pass but whose unit test fails.
fn committed_failing_crate(tag: &str) -> (TempDir, String) {
    let dir = TempDir::new(tag);
    write_crate(dir.path(), FAILING_TEST_LIB);
    write(&dir.path().join(".gitignore"), "/target\n");
    write(&dir.path().join("Cargo.lock"), LOCK);
    git(dir.path(), &["init", "-q"]);
    git(dir.path(), &["add", "."]);
    git(dir.path(), &["commit", "-q", "-m", "init"]);
    let head = git(dir.path(), &["rev-parse", "HEAD"]);
    (dir, head)
}

fn set_last_green(dir: &Path, level: &str, head: &str) {
    write(
        &dir.join("target/forge/state.json"),
        &json!({ "last_green": { "level": level, "head": head } }).to_string(),
    );
}

fn stop(dir: &Path) -> (i32, String) {
    let input = json!({ "session_id": "v", "cwd": dir, "hook_event_name": "Stop" });
    let out = run(&["hook", "stop"], dir, &input.to_string());
    (out.status.code().unwrap(), stdout(&out))
}

#[test]
fn stop_skips_gates_when_nothing_changed_since_green_head() {
    let (dir, head) = committed_failing_crate("v-stop-skip");
    set_last_green(dir.path(), "full", &head);
    write(&dir.path().join("notes.md"), "not rust\n");
    assert_eq!(stop(dir.path()), (0, String::new()));
    // A changed `*.rs` file makes the gates run again; the failing test blocks.
    write(
        &dir.path().join("src/lib.rs"),
        &format!("{FAILING_TEST_LIB}// touched\n"),
    );
    let (code, out) = stop(dir.path());
    assert_eq!(code, 0);
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["decision"], "block", "{out}");
}

#[test]
fn stop_runs_full_gates_after_only_a_fast_green() {
    let (dir, _) = committed_failing_crate("v-stop-fast");
    let fast = run(&["gates", "fast"], dir.path(), "");
    assert_eq!(fast.status.code(), Some(0), "{}", stdout(&fast));
    let (code, out) = stop(dir.path());
    assert_eq!(code, 0);
    let v: Value = serde_json::from_str(&out).unwrap();
    assert_eq!(v["decision"], "block", "{out}");
    assert!(v["reason"].as_str().unwrap().contains("FAIL G3"), "{out}");
}

#[test]
fn post_edit_runs_rustfmt_and_ignores_non_rust_files() {
    let dir = TempDir::new("v-post-edit");
    write_crate(dir.path(), BADLY_FORMATTED_LIB);
    let input = |file: &str| {
        json!({
            "cwd": dir.path(),
            "hook_event_name": "PostToolUse",
            "tool_name": "Write",
            "tool_input": { "file_path": dir.path().join(file) }
        })
        .to_string()
    };
    let out = run(&["hook", "post-edit"], dir.path(), &input("Cargo.toml"));
    assert_eq!((out.status.code(), stdout(&out)), (Some(0), String::new()));
    let lib = dir.path().join("src/lib.rs");
    assert_eq!(std::fs::read_to_string(&lib).unwrap(), BADLY_FORMATTED_LIB);
    let out = run(&["hook", "post-edit"], dir.path(), &input("src/lib.rs"));
    assert_eq!((out.status.code(), stdout(&out)), (Some(0), String::new()));
    assert_eq!(
        std::fs::read_to_string(&lib).unwrap(),
        "pub fn add_one(x: u32) -> u32 {\n    x + 1\n}\n"
    );
}

#[test]
fn diag_dedupes_same_error_from_lib_and_test_targets() {
    let msg = |kind: &str| {
        json!({
            "reason": "compiler-message",
            "target": { "kind": [kind], "name": "demo" },
            "message": {
                "level": "error",
                "message": "mismatched types",
                "code": { "code": "E0308" },
                "spans": [{ "file_name": "src/lib.rs", "line_start": 4, "column_start": 5, "is_primary": true }],
                "children": [],
                "rendered": "error[E0308]: mismatched types\n"
            }
        })
        .to_string()
    };
    let input = format!("{}\n{}\n", msg("lib"), msg("test"));
    let s = forge_tools::diag::summarize(&input);
    assert_eq!((s.errors, s.warnings), (1, 0), "{}", s.text);
}
